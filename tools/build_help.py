#!/usr/bin/env python3
"""The documentation as pages served by the module, linked from its About page.

docs/*.md and RELEASE-NOTES.md become ebx-layout-designer/src/main/webapp/www/help/*.html: static pages, no script, a
Content-Security-Policy that loads nothing from elsewhere, the version of VERSION in the top bar. Links between these
documents point to the pages; links to other files of the repository become plain text. Modelled on
ebx-data-catalog's tools/build_help.py.

    python3 tools/build_help.py          write the pages
    python3 tools/build_help.py --check  fail when a page is not what its Markdown gives (run by tools/package.sh)
"""
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'ebx-layout-designer', 'src', 'main', 'webapp', 'www', 'help')
# source (from the repository root), page, language, title
PAGES = [
    ('docs/USER-GUIDE.md', 'user-guide.html', 'en', 'User guide'),
    ('docs/USER-GUIDE.fr.md', 'guide-utilisateur.html', 'fr', 'Guide de l’utilisateur'),
    ('docs/INSTALL.md', 'install.html', 'en', 'Installation'),
    ('docs/LAYOUT-FORMAT.md', 'layout-format.html', 'en', 'Layout format'),
    ('RELEASE-NOTES.md', 'release-notes.html', 'en', 'Release notes'),
]
LINKS = {os.path.basename(source): page for source, page, _, _ in PAGES}
STYLE = (
    ':root{color-scheme:light}body{font:15px/1.55 -apple-system,"Segoe UI",Helvetica,Arial,sans-serif;color:#222;max-width:1000px;'
    'margin:24px auto;padding:0 24px;background:#fff}h1{font-size:28px;border-bottom:2px solid #0e6f8f;padding-bottom:6px}'
    'h2{font-size:21px;margin-top:36px;border-bottom:1px solid #ddd;padding-bottom:4px}h3{font-size:17px;margin-top:24px}'
    'table{border-collapse:collapse;margin:12px 0;font-size:14px}th,td{border:1px solid #ddd;padding:6px 10px;text-align:left;'
    'vertical-align:top}th{background:#f3f5f8}code{font:13px Menlo,Consolas,monospace;background:#f4f5f7;padding:1px 4px;'
    'border-radius:3px}pre{background:#f4f5f7;padding:10px 12px;overflow-x:auto;border-radius:4px}pre code{padding:0}'
    'a{color:#0e6f8f}a:focus-visible{outline:3px solid #0e6f8f;outline-offset:2px}.help-top{display:flex;justify-content:'
    'space-between;gap:12px;flex-wrap:wrap;font-size:14px;color:#555;border-bottom:1px solid #eee;padding-bottom:8px}'
    '.help-top nav{display:flex;gap:14px;flex-wrap:wrap}'
)
POLICY = "default-src 'none'; style-src 'unsafe-inline'; img-src 'self' data:; base-uri 'none'; form-action 'none'"


def version():
    with open(os.path.join(ROOT, 'VERSION'), encoding='utf-8') as f:
        return f.read().strip()


def convert(text):
    import markdown  # python-markdown, used only here

    def link(m):
        label, target = m.group(1), m.group(2)
        if target.startswith(('#', 'http:', 'https:')):
            return m.group(0)
        name, _, anchor = target.partition('#')
        page = LINKS.get(os.path.basename(name))
        return '[%s](%s%s)' % (label, page, '#' + anchor if anchor else '') if page else label

    text = re.sub(r'(?m)^!\[[^\]]*\]\([^)]*\)\s*\n', '', text)
    text = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', link, text)
    return markdown.markdown(text, extensions=['tables', 'toc', 'sane_lists', 'fenced_code'], output_format='html')


def page(source, lang, title, v):
    with open(os.path.join(ROOT, source), encoding='utf-8') as f:
        body = convert(f.read())
    nav = ' '.join('<a href="%s" hreflang="%s">%s</a>' % (p, l, html.escape(t)) for _, p, l, t in PAGES)
    return ('<!DOCTYPE html>\n<html lang="%s">\n<head>\n<meta charset="utf-8">\n'
            '<meta http-equiv="Content-Security-Policy" content="%s">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>ON EBX Layout Designer — %s</title>\n'
            '<style>%s</style>\n</head>\n<body>\n'
            '<!-- Generated by tools/build_help.py from %s: edit the Markdown, then run the script. -->\n'
            '<div class="help-top"><span>ON EBX Layout Designer %s</span><nav aria-label="documentation">%s</nav></div>\n'
            '<main>\n%s\n</main>\n</body>\n</html>\n') % (lang, POLICY, html.escape(title), STYLE, source, html.escape(v), nav, body)


def main():
    check = '--check' in sys.argv
    v = version()
    stale = []
    os.makedirs(OUT, exist_ok=True)
    for source, target, lang, title in PAGES:
        content = page(source, lang, title, v)
        path = os.path.join(OUT, target)
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if check:
            if current != content:
                stale.append(target)
            ids = set(re.findall(r'id="([^"]+)"', content))
            broken = sorted(set(re.findall(r'href="#([^"]+)"', content)) - ids)
            if broken:
                stale.append(target + ' (links to missing sections: ' + ', '.join(broken) + ')')
        elif current != content:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(content)
            print('wrote', os.path.relpath(path, ROOT))
    if stale:
        print('FAIL: help pages out of date: %s (run python3 tools/build_help.py)' % ', '.join(stale), file=sys.stderr)
        return 1
    if check:
        print('PASS: %d help pages match their Markdown' % len(PAGES))
    return 0


if __name__ == '__main__':
    sys.exit(main())
