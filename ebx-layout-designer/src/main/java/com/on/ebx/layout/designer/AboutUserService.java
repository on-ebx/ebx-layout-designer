/**
 * The About page: the build of the module (version, commit, build date), the ON EBX it runs on, a line to copy into a
 * support request, and the documentation served by the module ({@code www/help}, generated by {@code tools/build_help.py}).
 */
public final class AboutUserService implements UserService<TableViewEntitySelection>
{
	/** A colour of the perspective goes into a style block: only a plain hex or rgb() value passes. */
	private static final Pattern COLOUR = Pattern.compile("#[0-9a-fA-F]{3}|#[0-9a-fA-F]{6}|rgb\\(\\s*\\d{1,3}\\s*,\\s*\\d{1,3}\\s*,\\s*\\d{1,3}\\s*\\)");

	/**
	 * The Copy button: the clipboard API, else a hidden text area and execCommand (the clipboard API is refused in some
	 * frames), else the line is selected for the user to copy.
	 */
	private static final String COPY_JS = "(function(){var b=document.getElementById('ld-about-copy');if(!b)return;"
		+ "var line=document.getElementById('ld-about-line'),s=document.getElementById('ld-about-copied');"
		+ "var say=function(k){s.textContent=b.getAttribute(k);};"
		+ "var fallback=function(){var a=document.createElement('textarea');a.value=line.textContent;a.style.position='fixed';a.style.opacity='0';"
		+ "document.body.appendChild(a);a.select();var ok=false;try{ok=document.execCommand('copy');}catch(e){}document.body.removeChild(a);"
		+ "if(ok){say('data-done');}else{var r=document.createRange();r.selectNodeContents(line);var sel=window.getSelection();sel.removeAllRanges();"
		+ "sel.addRange(r);say('data-select');}};"
		+ "b.addEventListener('click',function(){if(navigator.clipboard&&window.isSecureContext){navigator.clipboard.writeText(line.textContent)"
		+ ".then(function(){say('data-done');},fallback);}else{fallback();}});})();";

	@Override
	public void setupObjectContext(final UserServiceSetupObjectContext<TableViewEntitySelection> pContext, final UserServiceObjectContextBuilder pBuilder)
	{
		// nothing to edit
	}

	@Override
	public void setupDisplay(final UserServiceSetupDisplayContext<TableViewEntitySelection> pContext, final UserServiceDisplayConfigurator pConfigurator)
	{
		final Session session = pContext.getSession();
		final Locale locale = session.getLocale();
		final String main = AboutUserService.mainColour(pContext);
		pConfigurator.setTitle(Messages.get(locale, "about.label"));
		final UIButtonSpecNavigation close = pConfigurator.newCloseButton();
		close.setAskBeforeLeavingModifiedForm(false);
		pConfigurator.setRightButtons(close);
		pConfigurator.setContent(new UserServicePane()
		{
			@Override
			public void writePane(final UserServicePaneContext pPaneContext, final UserServicePaneWriter pWriter)
			{
				pWriter.add(AboutUserService.html(locale, session.isUserInRole(Profile.ADMINISTRATOR), main));
				pWriter.addJS_cr(AboutUserService.COPY_JS);
			}
		});
	}

	static String html(final Locale pLocale, final boolean pAdministrator, final String pMainColour)
	{
		final String help = "/" + LayoutPaths.MODULE_NAME + "/www/help/";
		final boolean french = "fr".equals(pLocale.getLanguage());
		final StringBuilder h = new StringBuilder();
		h.append("<style>.ld-about{--ld-main:").append(pMainColour == null ? "#0e6f8f" : pMainColour)
			.append(";max-width:820px;padding:16px 24px;font:14px/1.5 -apple-system,\"Segoe UI\",Helvetica,Arial,sans-serif;color:#172033}")
			.append(".ld-about h2{font-size:20px;margin:0 0 4px}.ld-about h3{font-size:15px;margin:22px 0 8px;border-bottom:2px solid var(--ld-main);padding-bottom:4px}")
			.append(".ld-about p{margin:0 0 8px;color:#4a5568}.ld-about dl{display:grid;grid-template-columns:max-content 1fr;gap:6px 18px;margin:0}")
			.append(".ld-about dt{color:#4a5568}.ld-about dd{margin:0;font-weight:600}.ld-about code{font:13px Menlo,Consolas,monospace}")
			.append(".ld-about ul{margin:0;padding-left:18px}.ld-about li{margin:4px 0}.ld-about a{color:var(--ld-main)}")
			.append(".ld-about .ld-line{display:flex;gap:10px;align-items:center;flex-wrap:wrap;margin-top:12px;padding:8px 10px;background:#f4f5f7;border-radius:4px}")
			.append(".ld-about button{border:1px solid var(--ld-main);background:#fff;color:var(--ld-main);border-radius:4px;padding:3px 10px;cursor:pointer}")
			.append(".ld-about small{color:#4a5568}</style>");
		h.append("<div class=\"ld-about\"><h2>ON EBX Layout Designer</h2><p>").append(AboutUserService.esc(Messages.get(pLocale, "about.intro"))).append("</p>");

		h.append("<h3>").append(AboutUserService.esc(Messages.get(pLocale, "about.version"))).append("</h3><dl>");
		AboutUserService.row(h, Messages.get(pLocale, "about.version"), ModuleVersion.version());
		AboutUserService.row(h, Messages.get(pLocale, "about.commit"), ModuleVersion.commit());
		AboutUserService.row(h, Messages.get(pLocale, "about.builtAt"), AboutUserService.date(ModuleVersion.builtAt(), pLocale));
		AboutUserService.row(h, "ON EBX", ModuleVersion.ebx());
		h.append("</dl>");
		if (!ModuleVersion.isStamped())
		{
			h.append("<p><small>").append(AboutUserService.esc(Messages.get(pLocale, "about.unstamped"))).append("</small></p>");
		}
		h.append("<div class=\"ld-line\"><code id=\"ld-about-line\">").append(AboutUserService.esc(ModuleVersion.supportLine())).append("</code>")
			.append("<button type=\"button\" id=\"ld-about-copy\" data-done=\"").append(AboutUserService.esc(Messages.get(pLocale, "about.copied")))
			.append("\" data-select=\"").append(AboutUserService.esc(Messages.get(pLocale, "about.selected"))).append("\">")
			.append(AboutUserService.esc(Messages.get(pLocale, "about.copy"))).append("</button><small id=\"ld-about-copied\" role=\"status\"></small></div>");

		h.append("<h3>").append(AboutUserService.esc(Messages.get(pLocale, "about.docs"))).append("</h3><ul>");
		AboutUserService.link(h, AboutServiceDeclaration.guideUrl(pLocale), Messages.get(pLocale, "about.guide"), french ? "fr" : "en");
		AboutUserService.link(h, help + (french ? "user-guide.html" : "guide-utilisateur.html"),
			french ? "User guide (English)" : "Guide de l’utilisateur (français)", french ? "en" : "fr");
		AboutUserService.link(h, help + "release-notes.html", Messages.get(pLocale, "about.releaseNotes"), "en");
		if (pAdministrator)
		{
			AboutUserService.link(h, help + "install.html", Messages.get(pLocale, "about.install"), "en");
			AboutUserService.link(h, help + "layout-format.html", Messages.get(pLocale, "about.format"), "en");
		}
		h.append("</ul></div>");
		return h.toString();
	}

	/** The build time, stamped in UTC, in the user's locale and the server's time zone; as stamped when it does not parse. */
	static String date(final String pStamp, final Locale pLocale)
	{
		try
		{
			final java.text.SimpleDateFormat iso = new java.text.SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss'Z'", Locale.ROOT);
			iso.setTimeZone(TimeZone.getTimeZone("UTC"));
			final Date d = iso.parse(pStamp);
			return DateFormat.getDateTimeInstance(DateFormat.LONG, DateFormat.SHORT, pLocale).format(d);
		}
		catch (final java.text.ParseException ex)
		{
			return pStamp;
		}
	}

	private static void row(final StringBuilder h, final String pLabel, final String pValue)
	{
		h.append("<dt>").append(AboutUserService.esc(pLabel)).append("</dt><dd>").append(AboutUserService.esc(pValue)).append("</dd>");
	}

	private static void link(final StringBuilder h, final String pUrl, final String pLabel, final String pLang)
	{
		h.append("<li><a href=\"").append(AboutUserService.esc(pUrl)).append("\" hreflang=\"").append(pLang)
			.append("\" target=\"_blank\" rel=\"noopener\">").append(AboutUserService.esc(pLabel)).append("</a></li>");
	}

	private static String mainColour(final UserServiceRequest pRequest)
	{
		try
		{
			final Perspective perspective = pRequest.getCurrentPerspective();
			final PerspectiveTheme theme = perspective == null ? null : perspective.getTheme();
			final String colour = theme == null ? null : theme.getMainColor();
			return colour != null && AboutUserService.COLOUR.matcher(colour.trim()).matches() ? colour.trim() : null;
		}
		catch (final RuntimeException ex)
		{
			return null;
		}
	}

	static String esc(final String s)
	{
		return DesignerUserService.esc(s);
	}

	@Override
	public void validate(final UserServiceValidateContext<TableViewEntitySelection> pContext)
	{
		// nothing to validate
	}

	@Override
	public UserServiceEventOutcome processEventOutcome(final UserServiceProcessEventOutcomeContext<TableViewEntitySelection> pContext, final UserServiceEventOutcome pOutcome)
	{
		return pOutcome;
	}
}
